// Orders the 169 starting hands for the bots' "top X% of hands" ranges, and writes
// src/engine/hu/preflopRank.js. Run: node scripts/preflop-rank.mjs
//
// Equity against a random hand is the wrong order for a range: it puts K2o and Q3s ahead of 65s,
// 87s and T8o, hands every real range opens first. So hands are ranked by the position charts
// (ranges.js): the hands an early-position open contains come first, then what middle position
// adds, the cutoff, the button, the heads-up button, the big blind's defence, and the rest; equity
// against a random hand (Monte Carlo, seeded) orders hands within a tier.
// The bots' fitted numbers are shares of all hands, so their frequencies do not change with the
// order; what changes is which hands make up each range.
import { writeFileSync } from 'node:fs';
import { evaluate } from '../src/engine/hu/hand.js';
import { rng } from '../src/engine/hu/game.js';
import { RFI_RANGES, HU_BTN_OPEN, FACING_OPEN } from '../src/engine/ranges.js';

const R = '23456789TJQKA';
const rand = rng(2026);
const hands = [];
for (let a = 12; a >= 0; a--) for (let b = a; b >= 0; b--) {
  if (a === b) hands.push({ key: R[a] + R[b], cards: [4 * a, 4 * b + 1] });
  else {
    hands.push({ key: R[a] + R[b] + 's', cards: [4 * a, 4 * b] });
    hands.push({ key: R[a] + R[b] + 'o', cards: [4 * a, 4 * b + 1] });
  }
}
const N = 6000;
for (const h of hands) {
  let win = 0;
  for (let i = 0; i < N; i++) {
    const deck = [];
    for (let c = 0; c < 52; c++) if (c !== h.cards[0] && c !== h.cards[1]) deck.push(c);
    for (let k = 0; k < 7; k++) { const j = k + Math.floor(rand() * (deck.length - k)); [deck[k], deck[j]] = [deck[j], deck[k]]; }
    const opp = [deck[0], deck[1]], b = deck.slice(2, 7);
    const v1 = evaluate([...h.cards, ...b]), v2 = evaluate([...opp, ...b]);
    win += v1 > v2 ? 1 : v1 === v2 ? 0.5 : 0;
  }
  h.eq = win / N;
}
const bb = FACING_OPEN['BB|BTN'];
const TIERS = [RFI_RANGES.UTG, RFI_RANGES.MP, RFI_RANGES.CO, RFI_RANGES.BTN, HU_BTN_OPEN, new Set([...bb.raise, ...bb.call])];
const tierOf = (k) => { const t = TIERS.findIndex(set => set.has(k)); return t < 0 ? TIERS.length : t; };
hands.sort((x, y) => tierOf(x.key) - tierOf(y.key) || y.eq - x.eq);
const combos = (k) => (k.length === 2 ? 6 : k.endsWith('s') ? 4 : 12);
let cum = 0;
const rows = hands.map(h => { cum += combos(h.key); return [h.key, +h.eq.toFixed(3), +(cum / 1326).toFixed(4)]; });
writeFileSync('src/engine/hu/preflopRank.js',
  `// Generated by scripts/preflop-rank.mjs: the 169 starting hands in range order — by the position\n` +
  `// charts (early, middle, cutoff, button, heads-up button, big-blind defence, the rest), equity vs\n` +
  `// a random hand within a tier. [hand, equity vs random, cumulative share of all 1326 combos]\n` +
  `export const PREFLOP_RANK = ${JSON.stringify(rows)};\n`);
const at = (k) => rows.find(r => r[0] === k);
console.log(['AA', '65s', 'T8o', 'K2o', 'Q3s', '98o', 'J7o', 'K5o', '72o'].map(k => `${k} ${at(k)[2]}`).join('  '));
console.log('tier ends:', TIERS.map(t => { let c = 0; for (const r of rows) if (t.has(r[0])) c = r[2]; return c; }));
